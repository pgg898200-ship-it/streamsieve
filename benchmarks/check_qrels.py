"""Cross-check ordered top five on the four-run Robust03 replay and its judgments."""
import argparse
from collections import defaultdict
from fractions import Fraction
import hashlib
import json
from math import log2
from pathlib import Path
from statistics import mean
import sys
from urllib.request import urlopen

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from rankfence import Fence

REVISION = "8a896def007e3d657eb29f820ee3de98e2f32691"
QRELS = f"https://raw.githubusercontent.com/joaopalotti/trectools/{REVISION}/examples/robust03/qrel/robust03_qrels.txt"
QRELS_SHA = "809a8502f3865ea437714e692b601770ea7c9b70b294f4c391a38bf4bcfe7fd5"
TRACE_SHA = "0c4b02522c49436f2ac3eca6c44c6853b0f6acad217ee62e631564297e17c3ea"


def dcg(grades):
    return sum((2**g - 1) / log2(i + 2) for i, g in enumerate(grades))


def main():
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("trace", type=Path, help="JSON generated by fetch_replay.py robust03")
    cli.add_argument("--qrels", type=Path, help="offline copy of robust03_qrels.txt")
    args = cli.parse_args()
    if args.qrels is None:
        with urlopen(QRELS, timeout=60) as response:
            raw_qrels = response.read()
    else:
        raw_qrels = args.qrels.read_bytes()
    raw_trace = args.trace.read_bytes()
    for name, data, expected in [("qrels", raw_qrels, QRELS_SHA), ("trace", raw_trace, TRACE_SHA)]:
        if hashlib.sha256(data).hexdigest() != expected:
            raise ValueError(f"{name} checksum mismatch")

    judgments = defaultdict(dict)
    for line in raw_qrels.decode("ascii").splitlines():
        query, _, doc, relevance = line.split()
        judgments[query][doc] = int(relevance)
    rows_read = 0
    early = 0
    ndcg = []
    for query in json.loads(raw_trace)["queries"]:
        topic, lists = query["id"], query["lists"]
        scores = defaultdict(Fraction)
        for docs in lists:
            for rank, doc in enumerate(docs, 1):
                scores[doc] += Fraction(1, 60 + rank)
        expected = tuple(sorted(scores, key=lambda d: (-scores[d], d))[:5])
        fence = Fence(len(lists), 5)
        for offset in range(0, 1000, 32):
            for i, docs in enumerate(lists):
                fence.push(i, docs[offset:offset + 32], done=offset + 32 >= len(docs))
            if fence.ordered() is not None:
                break
        if expected != fence.ordered():
            raise AssertionError(f"exact ranking differs for topic {topic}")
        grades = judgments[topic]
        ideal = dcg(sorted(grades.values(), reverse=True)[:5])
        ndcg.append(dcg([grades.get(doc, 0) for doc in expected]) / ideal if ideal else 0)
        rows_read += sum(fence.depths)
        early += sum(fence.depths) < sum(map(len, lists))
    print(json.dumps({"topics": len(ndcg), "early": early, "rows_read": rows_read,
                      "mean_ndcg_at_5": mean(ndcg), "qrels_sha256": QRELS_SHA}, indent=2))


if __name__ == "__main__":
    main()
